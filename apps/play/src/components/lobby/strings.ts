export type LobbyStringKey = keyof typeof strings;

export function t(key: LobbyStringKey): string {
  return strings[key];
}

export function format(template: string, values: Record<string, string | number>): string {
  // Minimal ICU subset: `{name, plural, one {…} other {…}}` blocks used by the
  // waiting-for-seats/readiness strings.
  const withPlurals = template.replace(
    /\{(\w+),\s*plural,\s*one\s*\{([^{}]*)\}\s*other\s*\{([^{}]*)\}\}/g,
    (match, name: string, one: string, other: string) => {
      const value = Number(values[name]);
      if (!Number.isFinite(value)) return match;
      return value === 1 ? one : other;
    },
  );
  return withPlurals.replace(/\{(\w+)\}/g, (match, name: string) =>
    name in values ? String(values[name]) : match,
  );
}
